import assert from 'node:assert/strict';
import {legacyContract,validateDigitization} from '../../src/shop/fitting/digitization.js';
import {patternRecipe} from '../../src/shop/fitting/families.js';
import {recommendSize} from '../../src/shop/fitting/sizes.js';
import {garmentAssetKey} from '../../src/shop/fitting/asset-key.js';
const item={kind:'tee',shape:{cm:{chest:54,len:65},calibration:{measurements:{chest:{value_cm:54,method:'user-tape'}}}},sizes:[{name:'L',body:{chest:[104,108]},cm:{chest:56}}]};
item.digitization=legacyContract(item,{front:{sha256:'a'},back:{sha256:'b'}});
assert.equal(item.digitization.measurements.chest.estimated,false);
assert.equal(item.digitization.measurements.len.estimated,true);
assert.equal(item.digitization.sizes[0].measurements.chest.source,'body-chart-derived');
assert.deepEqual(validateDigitization(item).errors,[]);
const bad=structuredClone(item);bad.digitization.measurements.chest.basis='circumference';assert(validateDigitization(bad).errors.includes('base:chest:unit-basis'));
bad.digitization.pattern.family='woven-trousers';assert(validateDigitization(bad).errors.includes('kind-family-mismatch'));
bad.digitization.pattern.family='missing';assert(validateDigitization(bad).errors.includes('unknown-family'));
bad.digitization.pattern.family='knit-top';bad.digitization.pattern.version=2;assert(validateDigitization(bad).errors.includes('pattern-version'));
const skirt={kind:'skirt',pleats:true};assert.equal(patternRecipe(skirt).fabric,'skirtP');assert.equal(patternRecipe(skirt).topology,'skirt');
const dress={kind:'dress',puff:true};assert.equal(patternRecipe(dress).puff,true);assert.equal(patternRecipe(dress).flare,true);
const sized={kind:'tee',sizesT:[{name:'S',cm:{chest:46}},{name:'L',cm:{chest:54}},{name:'fake',estimated:true,cm:{chest:70}}]};
assert.equal(recommendSize(sized,{chest:100}),'L');assert.equal(recommendSize(sized,{chest:130}),null);
const key=garmentAssetKey(sized);sized.sizesT[1].cm.chest=55;assert.notEqual(garmentAssetKey(sized),key);
console.log('Digitization: provenance, construction routing, unsupported recipes, fit limits and cache invalidation passed.');
